    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String profileID = fldId.getText();
        String username = fldUsername.getText();
        String password = fldPassword.getText();
        
        if(profileID.isBlank() || username.isBlank() || password.isBlank()) {
            JOptionPane.showMessageDialog(this, "All values are required");
            return;
        }
        
        Person newPerson = new Person(profileID);
        business.getPersonDirectory().addPerson(newPerson);
        Profile employeeProfile = new EmployeeProfile(newPerson);
        business.getEmployeeDirectory().addProfile((EmployeeProfile) employeeProfile);
        UserAccount user = new UserAccount(employeeProfile, username, password);
        business.getUserAccountDirectory().addUserAccount(user);
        
        fldId.setText("");
        fldPassword.setText("");
        fldUsername.setText("");
        
        JOptionPane.showMessageDialog(this, "New Employee Registered.");
    }//GEN-LAST:event_btnSaveActionPerformed


